const fs = require('fs');
const path = require('path');

// Try to read .env file if it exists
try {
  const dotenv = require('dotenv');
  dotenv.config({ quiet: true });
} catch (e) {
  // dotenv might not be available or needed if env vars are set otherwise
}

const licenseKey = process.env.SYNC_FUSION_LICENSE_KEY || '';

const content = `// Auto-generated by scripts/gen-syncfusion-license.js
export const SYNC_FUSION_LICENSE_KEY = '${licenseKey}';
`;
const outputDir = path.join(__dirname, '../src/secrets');
const outputFile = path.join(outputDir, 'syncfusion-license.ts');

if (!fs.existsSync(outputDir)) {
  fs.mkdirSync(outputDir, { recursive: true });
}

fs.writeFileSync(outputFile, content);
console.log(`Generated ${outputFile} with license key length: ${licenseKey.length}`);
